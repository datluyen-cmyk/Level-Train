	}

	public static string BuildLookupDetail(string countryGdpGroup, double ecpm, int playCount)
	{
		Dictionary<string, double[]> dictionary = ((playCount <= 4) ? ColdStartThresholds : EstablishedThresholds);
		string text = ((playCount <= 4) ? "cold_start" : "established");
		string text2 = countryGdpGroup ?? string.Empty;
		if (!dictionary.TryGetValue(text2, out var value))
		{
			text2 = "other_region";
			value = dictionary["other_region"];
		}
		for (int i = 0; i < value.Length; i++)
		{
			if (ecpm <= value[i])
			{
				int num = (i + 1) * 5;
				return $"查表[{text}] region={text2} ecpm<={value[i]:F4}(P{num})";
			}
		}
		return $"查表[{text}] region={text2} ecpm>{value[^1]:F4}(P100)";
	}

	private static float LookupInternal(Dictionary<string, double[]> table, string countryGdpGroup, double ecpm)
	{
		if (!table.TryGetValue(countryGdpGroup ?? string.Empty, out var value))
		{
			value = table["other_region"];
		}
		for (int i = 0; i < value.Length; i++)
		{
			if (ecpm <= value[i])
			{
				return (float)((i + 1) * 5) / 100f;
			}
		}
		return 1f;
	}
